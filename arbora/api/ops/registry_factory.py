"""Offline declaration assembly; serving authority validation belongs to bootstrap."""

from __future__ import annotations

from inspect import iscoroutinefunction

from arbora.api.registry import Composite, OpSpec, Registry
from arbora.api.registry.eg_binding import (
    EgContractError,
    load_catalog,
    load_eg_bindings,
    load_generated_scopes,
)
from arbora.api.registry.pending_scopes import apply_pending_scopes


def get_registry() -> Registry:
    """Compose supported declarations and the engine's complete method catalog.

    This requires no live session or service bindings, so canonical generation
    can use the same registry as serving. Bootstrap must separately validate
    live authorities before exposing these declarations as usable operations.
    Provider failures propagate; there is no partial-registry fallback.
    """
    from . import (
        a2a_federation,
        a2a_media,
        a2a_peers,
        a2a_team,
        access,
        agent_library,
        agents,
        approvals,
        apps,
        artifacts,
        assistants,
        atlas,
        bookmarks,
        browser,
        bundle,
        bus,
        capacity,
        capacity_questions,
        catalog,
        certification,
        chats,
        config_layers,
        dashboard,
        dca,
        decide,
        decision_evidence,
        deploy,
        development,
        development_delivery,
        development_effects,
        development_scm,
        documents,
        domain_pack,
        ecosystem,
        entity,
        evolution,
        evolution_metrics,
        federation,
        finance,
        finance_changes,
        finance_delegation,
        finance_import,
        finance_orders,
        finance_receipts,
        fleet,
        fleet_city,
        fleet_deploy_watch,
        fleet_scaling,
        git_export,
        goals,
        governance,
        graph_changes,
        graph_limits,
        harness,
        identity,
        identity_mfa,
        identity_mode,
        ingest,
        knowledge,
        lifecycle,
        loops,
        maintenance,
        market_compute,
        market_detail,
        media,
        meeting,
        meetings,
        memory,
        messaging,
        models,
        ontology_objects,
        operator_audit,
        operator_surface,
        ops,
        participants,
        plans,
        policy,
        policy_review,
        preferences,
        processes,
        program,
        promote,
        prompts,
        query,
        query_engine,
        research,
        retrieval,
        retrieval_space,
        review,
        runs,
        schedules,
        schema,
        security,
        security_eval,
        serving_techniques,
        sessions,
        skills_discovery,
        skills_eval,
        skills_friction,
        skills_telemetry,
        skills_tier,
        source,
        swarm,
        telemetry,
        usage,
        viewport,
        wire_access,
        work,
        workbench,
        workspace_files,
        workstreams,
        write_back,
    )

    curated: list[OpSpec] = []
    for module in (
        a2a_federation,
        a2a_media,
        a2a_peers,
        a2a_team,
        access,
        agent_library,
        agents,
        approvals,
        apps,
        artifacts,
        assistants,
        bookmarks,
        browser,
        bundle,
        bus,
        capacity,
        capacity_questions,
        catalog,
        certification,
        chats,
        config_layers,
        decide,
        development,
        development_delivery,
        development_scm,
        development_effects,
        dashboard,
        dca,
        decision_evidence,
        git_export,
        deploy,
        documents,
        domain_pack,
        ecosystem,
        entity,
        evolution,
        evolution_metrics,
        federation,
        finance,
        governance,
        graph_changes,
        graph_limits,
        harness,
        finance_changes,
        finance_delegation,
        finance_import,
        finance_receipts,
        fleet,
        fleet_city,
        fleet_deploy_watch,
        fleet_scaling,
        identity,
        identity_mfa,
        identity_mode,
        atlas,
        goals,
        ingest,
        ontology_objects,
        knowledge,
        lifecycle,
        loops,
        finance_orders,
        maintenance,
        market_compute,
        market_detail,
        media,
        meeting,
        meetings,
        memory,
        messaging,
        write_back,
        models,
        operator_audit,
        operator_surface,
        ops,
        participants,
        plans,
        preferences,
        processes,
        program,
        policy,
        policy_review,
        promote,
        prompts,
        query,
        query_engine,
        research,
        retrieval,
        retrieval_space,
        review,
        runs,
        schedules,
        schema,
        security,
        security_eval,
        serving_techniques,
        sessions,
        skills_discovery,
        skills_eval,
        skills_friction,
        skills_telemetry,
        skills_tier,
        source,
        swarm,
        telemetry,
        usage,
        wire_access,
        viewport,
        work,
        workbench,
        workspace_files,
        workstreams,
    ):
        for op in module.operations():
            if isinstance(op.binding, Composite):
                namespace, _, name = op.binding.handler.rpartition(".")
                handler = getattr(module, name, None)
                if namespace != module.__name__ or not iscoroutinefunction(handler):
                    raise ValueError(
                        f"{op.id}: unsupported or unbound handler {op.binding.handler}"
                    )
            curated.append(op)
    engine_catalog = load_catalog()
    scopes = load_generated_scopes(engine_catalog)
    curated, errors = apply_pending_scopes(curated, scopes.keys())
    if errors:
        raise EgContractError("; ".join(errors))
    generated = load_eg_bindings(catalog=engine_catalog, curated_ops=curated)
    return Registry((*curated, *generated), catalog=engine_catalog)
